package dev.gravaai.core.json;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Locale;

import tools.jackson.core.PrettyPrinter;
import tools.jackson.core.SerializableString;
import tools.jackson.core.io.CharacterEscapes;
import tools.jackson.core.io.SerializedString;
import tools.jackson.core.json.JsonFactory;
import tools.jackson.core.util.DefaultIndenter;
import tools.jackson.core.util.DefaultPrettyPrinter;
import tools.jackson.core.util.Separators;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;
import tools.jackson.databind.node.JsonNodeFactory;

/**
 * JSON read/write rules shared by every store (plan §5.2).
 *
 * <p>Ported from {@code electron/ipc/utils.ts} and {@code electron/appSettingsStore.ts}. The JSON
 * produced here must stay byte-compatible with {@code JSON.stringify(value, null, 2)} while the
 * Electron app is still the reference implementation (plan §1.2.9): two-space indent, line feed
 * {@code \n}, {@code "key": value} (one space after the colon), empty object {@code {}} and empty
 * array {@code []}, no trailing newline. {@code JsonFormatTest} asserts this against fixtures
 * generated by Node's JSON.stringify.
 */
public final class Json {

	/** Shared mapper; only the string escapes differ from the jackson-databind defaults. */
	public static final JsonMapper MAPPER =
			JsonMapper.builder(JsonFactory.builder().characterEscapes(new JsonStringEscapes()).build()).build();

	/** {@code JSON.stringify(value, null, 2)} formatting; copied per write by Jackson. */
	private static final PrettyPrinter PRINT_FORMAT = printFormat();

	private Json() {}

	public static JsonNodeFactory nodeFactory() {
		return MAPPER.getNodeFactory();
	}

	/** Port of {@code stripJsonByteOrderMark} in {@code electron/ipc/utils.ts}. */
	public static String stripJsonByteOrderMark(String content) {
		return !content.isEmpty() && content.charAt(0) == BOM ? content.substring(1) : content;
	}

	/**
	 * Port of {@code parseJsonWithByteOrderMark}: {@code JSON.parse(stripJsonByteOrderMark(content))}.
	 *
	 * <p>Throws a {@link RuntimeException} for invalid or empty input, exactly like
	 * {@code JSON.parse}; callers that read stores treat that as "use the defaults" (plan §5.2).
	 */
	public static JsonNode parseJsonWithByteOrderMark(String content) {
		JsonNode parsed = MAPPER.readTree(stripJsonByteOrderMark(content));
		if (parsed == null || parsed.isMissingNode()) {
			// JSON.parse("") throws a SyntaxError; no caller may see a missing tree as success.
			throw new IllegalArgumentException("Cannot parse an empty JSON document");
		}
		return parsed;
	}

	/** {@code JSON.stringify(value, null, 2)}: no trailing newline, like the Electron stores. */
	public static String stringify(Object value) {
		return MAPPER.writer().with(PRINT_FORMAT).writeValueAsString(value);
	}

	/** Reads a UTF-8 JSON document; a leading UTF-8 byte order mark is tolerated. */
	public static JsonNode readFile(Path file) throws IOException {
		return parseJsonWithByteOrderMark(Files.readString(file, StandardCharsets.UTF_8));
	}

	/** Writes {@code JSON.stringify(value, null, 2)} as UTF-8; no trailing newline. */
	public static void writeFile(Path file, Object value) throws IOException {
		Files.writeString(file, stringify(value), StandardCharsets.UTF_8);
	}

	/**
	 * The exact layout {@code JSON.stringify(value, null, 2)} uses.
	 *
	 * <p>{@link DefaultPrettyPrinter} defaults differ in three ways: a space before the colon, a
	 * space inside empty objects/arrays, and no pretty printing of {@code {}} / {@code []}. The
	 * {@link Separators} overrides and the explicit {@link DefaultIndenter}s fix all three.
	 */
	/**
	 * {@code JSON.stringify} writes control characters as lowercase {@code \\u00xx} escapes while
	 * Jackson writes uppercase hex. Real settings files rarely contain control characters, but captions
	 * and transcripts can, and the format must stay byte-compatible (plan §5.2). The five short
	 * escapes ({@code \\b}, {@code \\t}, {@code \\n}, {@code \\f}, {@code \\r}) already match; the rest
	 * are emitted by {@link JsonStringEscapes}.
	 */
	private static PrettyPrinter printFormat() {
		Separators separators = Separators.createDefaultInstance()
				.withObjectNameValueSpacing(Separators.Spacing.AFTER)
				.withObjectEmptySeparator("")
				.withArrayEmptySeparator("");
		DefaultPrettyPrinter printer = new DefaultPrettyPrinter(separators);
		printer.indentObjectsWith(new DefaultIndenter("  ", "\n"));
		printer.indentArraysWith(new DefaultIndenter("  ", "\n"));
		return printer;
	}

	/**
	 * Lowercase hexadecimal escapes for control characters, like {@code JSON.stringify}.
	 *
	 * <p>Jackson writes uppercase hex digits; JSON.stringify uses lowercase for the control
	 * characters that have no short escape. The five short escapes already match and are left to
	 * Jackson's standard table.
	 */
	private static final class JsonStringEscapes extends CharacterEscapes {

		private final int[] asciiEscapes;

		JsonStringEscapes() {
			asciiEscapes = CharacterEscapes.standardAsciiEscapesForJSON();
			for (int ch = 0; ch < 0x20; ch++) {
				if (ch == '\b' || ch == '\t' || ch == '\n' || ch == '\f' || ch == '\r') {
					continue;
				}
				asciiEscapes[ch] = ESCAPE_CUSTOM;
			}
		}

		@Override
		public int[] getEscapeCodesForAscii() {
			return asciiEscapes;
		}

		@Override
		public SerializableString getEscapeSequence(int ch) {
			// Jackson asks for every character when escapes are installed; only the control
			// characters without a short escape are customised. Everything else stays raw, like
			// JSON.stringify does for non-ASCII text.
			if (ch >= 0x20 || ch == '\b' || ch == '\t' || ch == '\n' || ch == '\f' || ch == '\r') {
				return null;
			}
			return new SerializedString(String.format(Locale.ROOT, "\\u%04x", ch));
		}
	}

	private static final char BOM = (char) 0xFEFF;
}
